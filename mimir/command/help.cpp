bool reply_help(Call& call, std::string_view container) {
  if (call.args.size() < 2 || !iequals(call.args[1], "help")) return false;
  if (call.args.size() != 2) throw CommandError("ERR wrong number of arguments for '" + std::string(container) + "|help' command");
  for (const auto& [name, lines] : texts) {
    if (name != container) continue;
    call.reply.array(lines.size());
    for (auto line : lines) call.reply.simple(line);
    return true;
  }
  return false;
}

